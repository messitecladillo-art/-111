"""Operator-provided practice bank for the knowledge-test board.

The historical question bank is third-party material with unconfirmed
redistribution rights, so it is never shipped with the public source tree.
An operator may place a bank generated by tools/build-net-exam-bank.py on the
server and expose it only to signed-in invited members.
"""
import json
import os
import stat
import threading
from pathlib import Path

from shared.errors import ApiError

MAX_BANK_BYTES = 8 * 1024 * 1024
MAX_QUESTIONS = 20_000
QUESTION_TYPES = {"single", "multiple", "boolean"}


def _text(value, limit):
    return isinstance(value, str) and 0 < len(value) <= limit


def validate_bank(bank):
    """Structural contract shared with lib/net-exam-progress.ts parseExamBank."""
    if not isinstance(bank, dict) or not _text(bank.get("version"), 120):
        raise ValueError("bank version required")
    sources, questions = bank.get("sources"), bank.get("questions")
    if not isinstance(sources, list) or not isinstance(questions, list) or not 0 < len(questions) <= MAX_QUESTIONS:
        raise ValueError("bank sources and questions required")
    source_ids = set()
    for source in sources:
        if not isinstance(source, dict) or not _text(source.get("id"), 200) or source["id"] in source_ids:
            raise ValueError("invalid source")
        source_ids.add(source["id"])
    question_ids = set()
    for q in questions:
        if not isinstance(q, dict) or not _text(q.get("id"), 200) or q["id"] in question_ids:
            raise ValueError("invalid question id")
        question_ids.add(q["id"])
        if q.get("type") not in QUESTION_TYPES or not _text(q.get("stem"), 4000) or not _text(q.get("chapter"), 200):
            raise ValueError("invalid question")
        options, answer = q.get("options"), q.get("answer")
        if not isinstance(options, list) or len(options) < 2 or not isinstance(answer, list) or not answer:
            raise ValueError("invalid options")
        option_ids = [o.get("id") if isinstance(o, dict) else None for o in options]
        if any(not _text(i, 40) for i in option_ids) or len(set(option_ids)) != len(option_ids):
            raise ValueError("invalid options")
        if any(not isinstance(o, dict) or not isinstance(o.get("text"), str) for o in options):
            raise ValueError("invalid options")
        if len(set(answer)) != len(answer) or any(a not in option_ids for a in answer):
            raise ValueError("invalid answer")
        if (q["type"] == "multiple") != (len(answer) > 1):
            raise ValueError("answer count does not match type")
        if q.get("answerStatus") != "valid":
            raise ValueError("question not source-verified")
        refs = q.get("sourceRefs")
        if not isinstance(refs, list) or any(not isinstance(r, dict) or r.get("sourceId") not in source_ids
                                             or not isinstance(r.get("locators"), list) for r in refs):
            raise ValueError("invalid source reference")
    return bank


class NetExamBank:
    """Reads the configured file once per (mtime, size) and keeps the encoded body."""

    def __init__(self, path: Path | None):
        self.path = path
        self._lock = threading.Lock()
        self._key = None
        self._body = None

    def body(self) -> bytes:
        unavailable = ApiError(404, "net_exam_bank_unavailable", "此服务器未配置网赛题库。")
        invalid = ApiError(503, "net_exam_bank_invalid", "服务器上的题库文件无法使用，请联系管理员。")
        if self.path is None:
            raise unavailable
        try:
            handle = self.path.open("rb")
        except FileNotFoundError:
            raise unavailable from None
        except OSError:
            raise invalid from None
        with handle, self._lock:
            # Stat and read the same open file so a replacement cannot bypass the size cap.
            info = os.fstat(handle.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_BANK_BYTES:
                raise invalid
            key = (info.st_mtime_ns, info.st_size)
            if key == self._key:
                return self._body
            self._key, self._body = None, None
            try:
                data = handle.read(MAX_BANK_BYTES + 1)
                if len(data) > MAX_BANK_BYTES:
                    raise ValueError("bank exceeds size cap")
                bank = validate_bank(json.loads(data.decode("utf-8")))
            except (OSError, UnicodeDecodeError, ValueError):
                raise invalid from None
            self._key = key
            self._body = json.dumps(bank, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
            return self._body
