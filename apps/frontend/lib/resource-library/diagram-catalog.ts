export function toDiagramGraphSpec(item: ResourceDiagramItem, topic?: string): DiagramGraphSpec {
  const cleanTopic = (topic ?? '').trim();
  return {
    direction: item.direction,
    nodes: [...item.nodes],
    edges: [...item.edges],
    roadmapMeta: cleanTopic ? { researchSubject: cleanTopic } : undefined,
  };
}

export async function buildDiagramInsert(item: ResourceDiagramItem, topic?: string): Promise<ReportInsert> {
  const cleanTopic = (topic ?? '').trim() || '调研课题';
  const id = `lib-diag-${item.id}-${Date.now().toString(36)}`;
  const snapshot = await buildDiagramResultSnapshot({
    id,
    title: `${cleanTopic}·${item.title}`,
    spec: toDiagramGraphSpec(item, cleanTopic),
    classification: 'public',
    sourceName: `EVI-X 资料库无边框研究框架“${item.title}”`,
  });
  return {
    id: `insert-${id}`,
    node: item.targetNode,
    source: `资料库 · ${item.title}`,
    items: [
      { kind: 'table', result: snapshot, caption: `${cleanTopic} ${item.title}节点台账` },
      { kind: 'figure', result: snapshot, caption: `${cleanTopic} ${item.title}` },
      { kind: 'paragraph', text: `如[[图:@1]]所示，${item.usageSummary}（各研究节点对应逻辑路径及输入输出边界详见[[表:@0]]）。` },
    ],
  };
}
