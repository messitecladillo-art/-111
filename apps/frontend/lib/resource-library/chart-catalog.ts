export async function buildChartSampleInsert(item: ResourceChartItem, topic?: string): Promise<ReportInsert> {
  const cleanTopic = (topic ?? '').trim() || '调研主题';
  const id = `lib-chart-${item.id}-${Date.now().toString(36)}`;
  const tpl = sampleTemplateForMethod(item.resultMethod);
  const rawMeta = { id, title: `${cleanTopic}·${item.title}（占位待替换实测数）`, headers: tpl.headers, rows: tpl.rows };
  const hash = await digestText(JSON.stringify(rawMeta));
  const unsigned = parseResultSnapshot({
    id,
    title: `${cleanTopic}·${item.title}参考模版`,
    sourceName: `EVI-X 资料库“${item.title}”参考模版（请替换为实测结果）`,
    sourceUrl: '',
    sourceHash: hash,
    resultHash: '0'.repeat(64),
    classification: 'simulated',
    method: tpl.snapshotMethod,
    n: 480,
    total: 480,
    headers: tpl.headers,
    rows: tpl.rows,
    metrics: [{ label: '参考模版样本数', value: 480 }],
    warnings: ['由资料库参考模版生成，正式提交前须替换为课题实测数据。'],
    variables: [item.title, `resource-chart:${item.id}`],
  });
  const result = { ...unsigned, resultHash: await digestText(JSON.stringify(resultPayload(unsigned))) };
  const cleanWhen = item.whenToUse.replace(/^(?:适用于|适配于?|可用于|用于|适合)/u, '').replace(/。$/u, '');
  const cleanPitfall = item.pitfallWarning.replace(/。$/u, '');
  return {
    id: `insert-${id}`,
    node: item.targetNode,
    source: `资料库 · ${item.title}`,
    items: [
      { kind: 'table', result, caption: `${cleanTopic} ${item.title}基础结果表（待替换为实测值）` },
      { kind: 'figure', result, caption: `${cleanTopic} ${item.title}` },
      { kind: 'paragraph', text: `如[[图:@1]]与[[表:@0]]所示，本图表参考结构适用于${cleanWhen}；解读实测结果时需注意${cleanPitfall}（正式提交前请替换为本课题实测数据）。` },
    ],
  };
}
